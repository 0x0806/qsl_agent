//! QSL brand for the terminal: the "Split state" mark as half-block art, the
//! two-colour palette, and company facts. Mirrors `BRAND.md` of the QSL site
//! (ink half + accent half; no gradients, no extra hues).
//!
//! Colour policy (clig.dev / no-color.org): nothing is coloured when stdout is
//! not a terminal, `NO_COLOR` is set, `TERM=dumb`, or `--no-color` is given.
//! The ink half uses the terminal's own foreground so it stays legible on any
//! background; the accent half is `#ff8a3d` (24-bit), xterm colour 208 (256
//! colours) or yellow (16 colours).

use colored::{Color, ColoredString, Colorize};
use std::sync::OnceLock;

pub const COMPANY: &str = "Quantum Secular Labs";
pub const WEBSITE: &str = "https://www.quantumsecularlabs.com/";
pub const PRODUCT_PAGE: &str = "https://www.quantumsecularlabs.com/qsl-agent";
pub const SUPPORT_EMAIL: &str = "support@quantumsecularlabs.com";
pub const REPOSITORY: &str = "https://github.com/0x0806/qsl_agent";
pub const TAGLINE: &str = "Local-first autonomous AI agent";
pub const COPYRIGHT: &str = "\u{a9} 2026 Quantum Secular Labs. All rights reserved.";

/// How many colours the terminal can show.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ColorLevel {
    None,
    Basic,
    Ansi256,
    TrueColor,
}

/// Pure detection logic, separated from the environment for testing.
pub fn detect_level(colorterm: &str, term: &str) -> ColorLevel {
    let ct = colorterm.to_ascii_lowercase();
    if ct.contains("truecolor") || ct.contains("24bit") {
        ColorLevel::TrueColor
    } else if term.contains("256color") || term == "xterm-kitty" || term == "alacritty" {
        ColorLevel::Ansi256
    } else {
        ColorLevel::Basic
    }
}

static LEVEL: OnceLock<ColorLevel> = OnceLock::new();

pub fn level() -> ColorLevel {
    if !colored::control::SHOULD_COLORIZE.should_colorize() {
        return ColorLevel::None;
    }
    *LEVEL.get_or_init(|| {
        let term = std::env::var("TERM").unwrap_or_default();
        if term == "dumb" {
            return ColorLevel::None;
        }
        detect_level(&std::env::var("COLORTERM").unwrap_or_default(), &term)
    })
}

/// The QSL accent colour (orange), degraded to what the terminal supports.
pub fn accent(s: &str) -> ColoredString {
    match level() {
        ColorLevel::TrueColor => s.truecolor(255, 138, 61),
        ColorLevel::Ansi256 => s.color(Color::AnsiColor(208)),
        _ => s.yellow(),
    }
}

/// The QSL "ink": the terminal foreground, emphasised.
pub fn ink(s: &str) -> ColoredString {
    s.bold()
}

/// Pixel rows of the mark: 'i' ink, 'a' accent, ' ' empty. Two pixel rows make
/// one terminal row (half blocks). Generated by `scripts/gen_logo.py`.
pub const MARK_PX: &[&str] = &[
    "                        ",
    "                        ",
    "      ii                ",
    "    iiii     aaaa       ",
    "  iiiii    aaaaaaaa     ",
    " iiiii   aaaaaaaaaaa    ",
    " iiii    aa   aaaaaaa   ",
    "iiii             aaaaa  ",
    "iiii              aaaaa ",
    "iiii               aaaa ",
    "iiii               aaaa ",
    "iiii                aaaa",
    "iiii                aaaa",
    " iiii               aaaa",
    " iiii               aaaa",
    " iiiii              aaaa",
    "  iiiii             aaaa",
    "   iiiiiii   ii    aaaa ",
    "    iiiiiiiiiii   aaaaa ",
    "     iiiiiiii    aaaaa  ",
    "       iiii     aaaa    ",
    "                aa      ",
    "                        ",
    "                        ",
];

pub const MARK_COLS: usize = 24;

/// The mark as terminal rows (24 columns wide), painted per the colour level.
pub fn mark_rows() -> Vec<String> {
    let none = level() == ColorLevel::None;
    let paint = |c: char, glyph: &str| -> String {
        if none {
            glyph.to_string()
        } else if c == 'i' {
            ink(glyph).to_string()
        } else {
            accent(glyph).to_string()
        }
    };
    MARK_PX
        .chunks(2)
        .map(|pair| {
            let top: Vec<char> = pair[0].chars().collect();
            let bot: Vec<char> = pair
                .get(1)
                .map_or_else(|| vec![' '; top.len()], |r| r.chars().collect());
            (0..top.len())
                .map(|x| {
                    let (t, b) = (top[x], bot[x]);
                    match (t, b) {
                        (' ', ' ') => " ".to_string(),
                        (t, b) if t == b => paint(t, "\u{2588}"),
                        (t, ' ') => paint(t, "\u{2580}"),
                        (' ', b) => paint(b, "\u{2584}"),
                        // two different halves in one cell: keep the upper one
                        (t, _) => paint(t, "\u{2580}"),
                    }
                })
                .collect()
        })
        .collect()
}

/// One-line wordmark for narrow terminals and plain output.
pub fn compact_mark() -> String {
    if level() == ColorLevel::None {
        "(QSL)".to_string()
    } else {
        format!("{}{}", ink("\u{25d6}"), accent("\u{25d7}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mark_is_rectangular() {
        assert!(MARK_PX.len().is_multiple_of(2));
        for r in MARK_PX {
            assert_eq!(r.chars().count(), MARK_COLS);
        }
    }

    #[test]
    fn mark_has_both_halves_and_fits_terminal_rows() {
        let all: String = MARK_PX.concat();
        assert!(all.contains('i') && all.contains('a'));
        assert_eq!(mark_rows().len(), MARK_PX.len() / 2);
    }

    #[test]
    fn colour_level_detection() {
        assert_eq!(detect_level("truecolor", "xterm"), ColorLevel::TrueColor);
        assert_eq!(detect_level("24bit", ""), ColorLevel::TrueColor);
        assert_eq!(detect_level("", "xterm-256color"), ColorLevel::Ansi256);
        assert_eq!(detect_level("", "linux"), ColorLevel::Basic);
    }
}
